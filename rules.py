"""번호·기한·판정 규칙. 업무설명_하자보수.md의 2~5절을 그대로 코드로 옮긴 것이다. AI는 쓰지 않는다."""
import csv
from datetime import date, timedelta
from pathlib import Path

BASE = Path(__file__).parent
공사정보_경로 = BASE / "data" / "공사정보.csv"

# 4절: 긴급도별 조치기한(접수일 + 일수)
기한일수 = {"긴급": 1, "높음": 3, "보통": 7}
만료임박일수 = 30  # 5절

확인필요 = "확인필요"


def 날짜(글):
    """'YYYY-MM-DD' 글을 date로 바꾼다."""
    return date.fromisoformat(str(글).strip())


def 공사목록읽기(경로=공사정보_경로):
    """공사정보.csv를 읽어 dict 목록으로 돌려준다. 원본은 고치지 않는다."""
    with open(경로, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def 대장읽기():
    """하자대장 읽기. 저장소(DB)는 db.py가 맡는다. DB가 필요 없는 규칙 함수는 db 없이도 쓸 수 있게 여기서 불러온다."""
    import db
    return db.대장읽기()


def 대장저장(행들):
    """하자대장 저장(접수번호 기준 덮어쓰기). (저장 건수, 건너뛴 건수)를 돌려준다."""
    import db
    return db.대장저장(행들)


def 접수번호(접수일, 순번):
    """HJ-접수일(YYYYMMDD)-순번(01부터). 예) HJ-20261102-01"""
    return f"HJ-{날짜(접수일):%Y%m%d}-{순번:02d}"


def 조치기한(접수일, 긴급도):
    """접수일 + 긴급 1일 / 높음 3일 / 보통 7일. 긴급도를 모르면 확인필요."""
    if 긴급도 not in 기한일수:
        return 확인필요
    return (날짜(접수일) + timedelta(days=기한일수[긴급도])).isoformat()


def 보증만료일(준공일, 보증기간_년):
    """준공일 + 하자보증기간(년)."""
    d = 날짜(준공일)
    return d.replace(year=d.year + int(보증기간_년)).isoformat()


def _공종후보(공종):
    """'설비/타일' 같은 후보 표기를 나눈다. 비었거나 확인필요면 빈 목록(공종 미정)."""
    후보 = [x.strip() for x in str(공종 or "").split("/") if x.strip()]
    if not 후보 or 확인필요 in 후보:
        return []
    return 후보


def 공사찾기(공사목록, 위치, 공종):
    """위치가 같고 공종이 후보에 들어가는 공사들. 공종 미정이면 위치만 같은 공사들."""
    후보 = _공종후보(공종)
    return [
        k for k in 공사목록
        if k["위치"] == 위치 and (not 후보 or k["공종"] in 후보)
    ]


def _남은일수(접수일, 만료일):
    return (날짜(만료일) - 날짜(접수일)).days


def _임박(접수일, 만료일):
    """보증만료일까지 30일 이내(만료 당일 포함)로 남았는가."""
    return 0 <= _남은일수(접수일, 만료일) <= 만료임박일수


def 판정(접수일, 위치, 공종, 공사목록):
    """접수일 기준 보증 판정. 대장의 공사번호~비고 칸을 dict로 돌려준다."""
    결과 = {
        "공사번호": "", "시공업체": "", "준공일": "", "보증만료일": "",
        "보증판정": 확인필요, "책임구분": 확인필요, "비고": "",
    }
    찾은 = 공사찾기(공사목록, 위치, 공종)

    # 맞는 공사가 없거나 2건 이상, 공종 미정 → 확인필요(담당자가 확인)
    if len(찾은) != 1 or not _공종후보(공종) or len(_공종후보(공종)) > 1:
        임박 = [
            k["공사번호"] for k in 찾은
            if _임박(접수일, 보증만료일(k["준공일"], k["하자보증기간(년)"]))
        ]
        if 임박:
            결과["비고"] = "만료임박(후보 " + ", ".join(임박) + ")"
        return 결과

    공사 = 찾은[0]
    만료일 = 보증만료일(공사["준공일"], 공사["하자보증기간(년)"])
    결과.update({
        "공사번호": 공사["공사번호"], "시공업체": 공사["시공업체"],
        "준공일": 공사["준공일"], "보증만료일": 만료일,
    })
    if 날짜(접수일) <= 날짜(만료일):  # 만료일 당일 포함
        결과["보증판정"], 결과["책임구분"] = "보증내", "시공업체"
        if _임박(접수일, 만료일):
            결과["비고"] = "만료임박"
    else:
        결과["보증판정"], 결과["책임구분"] = "보증만료", "자체보수"
    return 결과
