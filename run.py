"""접수함 폴더와 DB 접수(웹 접수 화면)를 모두 처리해 하자대장에 저장한다. 사용: python run.py"""
import sys
from pathlib import Path

import ai
import db
import rules

BASE = Path(__file__).parent
접수함 = BASE / "data" / "접수함"
대장경로 = BASE / "data" / "하자대장.csv"  # 예전 CSV 대장. 지금은 DB에 저장하고, 이 파일은 처음 한 번 옮길 때만 읽는다.

항목 = ["접수번호", "접수일", "원문파일", "위치", "공종", "하자내용", "긴급도", "조치기한",
        "공사번호", "시공업체", "준공일", "보증만료일", "보증판정", "책임구분", "상태", "비고"]


def 행만들기(원문파일, 결과, 순번, 공사목록):
    """AI가 정리한 결과 + 코드 규칙 → 대장 1행(dict)."""
    접수일, 위치, 공종, 긴급도 = 결과["접수일"], 결과["위치"], 결과["공종"], 결과["긴급도"]
    행 = {k: "" for k in 항목}
    행.update({
        "접수번호": rules.접수번호(접수일, 순번), "접수일": 접수일, "원문파일": 원문파일,
        "위치": 위치, "공종": 공종, "하자내용": 결과["하자내용"], "긴급도": 긴급도,
        "조치기한": rules.조치기한(접수일, 긴급도),
    })
    판정 = rules.판정(접수일, 위치, 공종, 공사목록)
    비고 = [판정.pop("비고")]
    행.update(판정)
    if len(결과["하자내용"]) > 40:
        비고.append("하자내용 40자 초과")
    행["비고"] = "; ".join(b for b in 비고 if b)
    행["상태"] = "확인필요" if 행["보증판정"] == rules.확인필요 else "판정완료"
    return 행


def 파일항목():
    """접수함 폴더의 원문들. 접수일은 AI가 원문에서 읽는다."""
    return [
        {"원문파일": p.name, "원문": p.read_text(encoding="utf-8"), "접수일": None, "접수id": None}
        for p in sorted(접수함.glob("*.txt"))
    ]


def DB항목():
    """DB 접수 테이블의 미처리 건. 발견일을 접수일로 쓴다. 접수자 이름은 AI에 보내지 않는다."""
    항목들 = []
    for r in db.미처리접수():
        발견일 = r["발견일"].isoformat() if r["발견일"] else None
        원문 = (f"[웹 접수] 발견일: {발견일}\n부서: {r['부서']}\n위치: {r['위치']}\n내용: {r['내용']}")
        항목들.append({"원문파일": f"DB접수-{r['id']}", "원문": 원문, "접수일": 발견일, "접수id": r["id"]})
    return 항목들


def 순번배정(접수일, 원문파일, 기존번호, 사용):
    """같은 원문은 예전 접수번호를 다시 쓰고, 새 원문은 그 날짜의 다음 순번을 받는다."""
    접두 = f"HJ-{접수일.replace('-', '')}-"
    예전 = 기존번호.get(원문파일, "")
    if 예전.startswith(접두):
        return int(예전[len(접두):])
    다음 = max([int(n[len(접두):]) for n in 사용 if n.startswith(접두)] + [0]) + 1
    사용.add(f"{접두}{다음:02d}")
    return 다음


def 처리(항목들, 공사목록, 위치목록, 기존번호):
    """원문 목록을 대장 행들로 만든다. (행들, DB 접수 완료 쌍[(id, 접수번호)])를 돌려준다."""
    사용 = set(기존번호.values())
    행들, 완료 = [], []
    for 항 in 항목들:
        근거 = ""
        try:
            결과 = ai.접수정리(항["원문"], 항["원문파일"], 위치목록)
            if 항["접수일"]:
                결과["접수일"] = 항["접수일"]  # DB 접수는 발견일이 접수일
            순번 = 순번배정(결과["접수일"], 항["원문파일"], 기존번호, 사용)
            행 = 행만들기(항["원문파일"], 결과, 순번, 공사목록)
            근거 = 결과.get("근거", "")
            if 항["접수id"]:
                완료.append((항["접수id"], 행["접수번호"]))
        except Exception as e:
            print(f"[오류] {항['원문파일']}: {e}", file=sys.stderr)
            행 = {k: "" for k in 항목}
            행.update({"원문파일": 항["원문파일"], "상태": "확인필요", "비고": f"처리 오류: {e}"})
        행들.append(행)
        print(f"{항['원문파일']} → {행['접수번호']} {행['공종']} {행['긴급도']} {행['보증판정']} | {근거}")
    return 행들, 완료


def main():
    공사목록 = rules.공사목록읽기()
    위치목록 = sorted({k["위치"] for k in 공사목록})
    try:
        기존번호 = {r["원문파일"]: r["접수번호"] for r in rules.대장읽기()}
        항목들 = 파일항목() + DB항목()
    except RuntimeError as e:
        sys.exit(f"[오류] DB를 읽지 못했습니다: {e}")

    행들, 완료 = 처리(항목들, 공사목록, 위치목록, 기존번호)

    try:
        저장, 건너뜀 = rules.대장저장(행들)
        db.접수처리완료(완료)  # 대장에 올린 DB 접수만 처리완료로 바꾼다
    except RuntimeError as e:
        sys.exit(f"\n[오류] 저장 실패: {e}")
    print(f"\n{저장}건 DB 저장(하자대장 테이블), DB 접수 {len(완료)}건 처리완료"
          + (f", 접수번호가 없어 {건너뜀}건은 저장하지 못함" if 건너뜀 else ""))


if __name__ == "__main__":
    main()
